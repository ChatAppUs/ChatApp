  ('ads_reviewer','Ad campaign review', ARRAY['ads.review','stats.view'], true)
ON CONFLICT (name) DO NOTHING;

-- Local payment rails per country (mobile money, bank, e-wallet, cash).
CREATE TABLE IF NOT EXISTS p2p_payment_methods (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  country_iso  TEXT NOT NULL,
  name         TEXT NOT NULL,
  kind         TEXT NOT NULL CHECK (kind IN ('mobile_money','bank_transfer','ewallet','cash','card')),
  created_at   TIMESTAMPTZ DEFAULT now(),
  UNIQUE (country_iso, name)
);

-- Buy/sell advertisements. Price is fiat per 1 unit of the crypto asset.
CREATE TABLE IF NOT EXISTS p2p_offers (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id        UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  side            TEXT NOT NULL CHECK (side IN ('buy','sell')),
  asset           TEXT NOT NULL,
  chain           TEXT NOT NULL,
  fiat_currency   TEXT NOT NULL,
  country_iso     TEXT NOT NULL,
  price           NUMERIC(38,18) NOT NULL CHECK (price > 0),
  min_amount      NUMERIC(38,18) NOT NULL DEFAULT 0,
  max_amount      NUMERIC(38,18) NOT NULL CHECK (max_amount > 0),
  payment_methods TEXT[] NOT NULL DEFAULT '{}',
  terms           TEXT NOT NULL DEFAULT '',
  active          BOOLEAN NOT NULL DEFAULT true,
  created_at      TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_p2p_offers ON p2p_offers(asset, chain, country_iso, side) WHERE active;

-- Escrowed trades. Crypto is locked at open, released on completion.
CREATE TABLE IF NOT EXISTS p2p_trades (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  offer_id       UUID NOT NULL REFERENCES p2p_offers(id),
  buyer_id       UUID NOT NULL REFERENCES users(id),
  seller_id      UUID NOT NULL REFERENCES users(id),
  asset          TEXT NOT NULL,
  chain          TEXT NOT NULL,
  crypto_amount  NUMERIC(38,18) NOT NULL CHECK (crypto_amount > 0),
  fiat_amount    NUMERIC(38,18) NOT NULL CHECK (fiat_amount > 0),
  fiat_currency  TEXT NOT NULL,
  payment_method TEXT NOT NULL,
  status         TEXT NOT NULL DEFAULT 'open'
                 CHECK (status IN ('open','paid','completed','cancelled','disputed','resolved_buyer','resolved_seller')),
  escrow_tx      UUID,
  release_tx     UUID,
  paid_at        TIMESTAMPTZ,
  created_at     TIMESTAMPTZ DEFAULT now(),
  updated_at     TIMESTAMPTZ DEFAULT now(),
  CHECK (buyer_id <> seller_id)
);
CREATE INDEX IF NOT EXISTS idx_p2p_trades_buyer ON p2p_trades(buyer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_p2p_trades_seller ON p2p_trades(seller_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_p2p_trades_disputes ON p2p_trades(status) WHERE status = 'disputed';

-- Admin-maintained USD rates. Conversion executes atomically in the
-- double-entry ledger.
CREATE TABLE IF NOT EXISTS convert_rates (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  asset       TEXT NOT NULL,
  chain       TEXT NOT NULL,
  usd_rate    NUMERIC(38,18) NOT NULL CHECK (usd_rate > 0),
  updated_by  UUID REFERENCES users(id),
  updated_at  TIMESTAMPTZ DEFAULT now(),
  UNIQUE (asset, chain)
);

CREATE TABLE IF NOT EXISTS conversions (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id     UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  from_asset  TEXT NOT NULL,
  from_chain  TEXT NOT NULL,
  to_asset    TEXT NOT NULL,
  to_chain    TEXT NOT NULL,
  from_amount NUMERIC(38,18) NOT NULL CHECK (from_amount > 0),
  to_amount   NUMERIC(38,18) NOT NULL CHECK (to_amount > 0),
  rate        NUMERIC(38,18) NOT NULL,
  ledger_tx   UUID NOT NULL,
  created_at  TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_conversions_user ON conversions(user_id, created_at DESC);

