-- 015_finance.sql - full crypto finance plane: deterministic multi-chain
-- deposit addresses, superadmin-signed withdrawal pipeline with sub-second
-- auto-approval, escrow-backed P2P marketplace with local payment rails for
-- every supported country, crypto convert engine, and dynamic admin roles.
BEGIN;

-- Per-feature switches so superadmin/finance control exactly which tokens can
-- be deposited, withdrawn, P2P-traded and converted.
ALTER TABLE platform_tokens
  ADD COLUMN IF NOT EXISTS deposit_enabled  BOOLEAN NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS withdraw_enabled BOOLEAN NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS p2p_enabled      BOOLEAN NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS convert_enabled  BOOLEAN NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS min_withdraw     NUMERIC(38,18) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS withdraw_fee     NUMERIC(38,18) NOT NULL DEFAULT 0;

-- Deterministic per-user deposit addresses derived in Go from
-- WALLET_MASTER_SEED (HMAC chain codes). The derivation path is stored so
-- custody-provider addresses can later replace self-custody ones cleanly.
CREATE TABLE IF NOT EXISTS deposit_addresses (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id      UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  asset        TEXT NOT NULL,
  chain        TEXT NOT NULL,
  address      TEXT NOT NULL,
  derivation   TEXT NOT NULL,
  created_at   TIMESTAMPTZ DEFAULT now(),
  UNIQUE (user_id, asset, chain),
  UNIQUE (chain, address)
);
CREATE INDEX IF NOT EXISTS idx_deposit_addr_user ON deposit_addresses(user_id);

-- Every withdrawal is a signed request. Status flow:
--   pending_review -> approved -> signed -> completed
--                            \-> rejected
-- The policy engine auto-approves + auto-signs clean requests in the same
-- transaction (<1s end to end). Flagged requests wait for an explicit
-- superadmin signature. Admins can approve/reject but can NEVER redirect or
-- execute funds themselves: execution binds the immutable to_address stored
-- at request time, and the ledger debit happens only here.
CREATE TABLE IF NOT EXISTS withdrawal_requests (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id       UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  asset         TEXT NOT NULL,
  chain         TEXT NOT NULL,
  to_address    TEXT NOT NULL,
  amount        NUMERIC(38,18) NOT NULL CHECK (amount > 0),
  fee           NUMERIC(38,18) NOT NULL DEFAULT 0,
  status        TEXT NOT NULL DEFAULT 'pending_review'
                CHECK (status IN ('pending_review','approved','signed','completed','rejected','failed')),
  risk_score    INT NOT NULL DEFAULT 0,
  risk_flags    TEXT[] NOT NULL DEFAULT '{}',
  auto_approved BOOLEAN NOT NULL DEFAULT false,
  approved_by   TEXT,
  approved_at   TIMESTAMPTZ,
  signature     TEXT,
  signed_at     TIMESTAMPTZ,
  tx_hash       TEXT,
  ledger_tx     UUID,
  created_at    TIMESTAMPTZ DEFAULT now(),
  updated_at    TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_withdraw_user ON withdrawal_requests(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_withdraw_status ON withdrawal_requests(status) WHERE status IN ('pending_review','approved','signed');

-- Superadmin-defined roles with a permission set. Built-in roles are seeded;
-- custom roles (e.g. p2p_manager, convert_manager, withdrawal_reviewer) can
-- be created/deleted at runtime. admin_roles.role references these defs.
CREATE TABLE IF NOT EXISTS admin_role_defs (
  name         TEXT PRIMARY KEY,
  description  TEXT NOT NULL DEFAULT '',
  permissions  TEXT[] NOT NULL DEFAULT '{}',
  built_in     BOOLEAN NOT NULL DEFAULT false,
  created_by   UUID REFERENCES users(id),
  created_at   TIMESTAMPTZ DEFAULT now()
);

